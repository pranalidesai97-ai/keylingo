#!/usr/bin/env python3
"""
Builds app/src/main/assets/emoji/emoji.tsv -- the bundled, offline emoji catalogue.

Source: emojibase-data 16.0.3 (npm, MIT, Miles Johnson); its labels and tags are
Unicode CLDR annotations (Unicode License v3). See assets/licenses/emoji-data-notices.txt.

Columns: emoji <TAB> category <TAB> unicode-emoji-version <TAB> english keywords <TAB> spanish keywords
  category  -- smileys people animals food travel activities objects symbols flags
               (emojibase groups 0,1,3..9; group 2 "component" and bare regional indicators are left out)
  keywords  -- lowercase words from the CLDR name and tags, space-separated, deduplicated
Rows are in Unicode's recommended order (emojibase "order"). Single emoji that already default to emoji
presentation are written without U+FE0F (Unicode's fully-qualified form). Skin-tone variants are not
included (the base emoji only). The keyboard hides, at run time, any emoji the device font
cannot draw, so emoji newer than the phone's Android version never show as empty boxes.

Usage: python3 -I tools/build_emoji_data.py <emojibase-data package dir> <out.tsv>
"""
import json
import re
import sys

CATEGORIES = {0: "smileys", 1: "people", 3: "animals", 4: "food", 5: "travel", 6: "activities", 7: "objects", 8: "symbols", 9: "flags"}


def normalised(entry):
    """emojibase adds U+FE0F to some emoji that already default to emoji presentation (type 1), e.g. U+1F44D.
    Unicode's fully-qualified form has no FE0F there, so it is dropped; text-default emoji (heavy black heart)
    keep the FE0F they need."""
    emoji = entry["emoji"]
    if entry.get("type") == 1 and len(emoji) == 2 and emoji.endswith("\ufe0f"):
        return emoji[0]
    return emoji


def words(entry):
    out = []
    for text in [entry.get("label", "")] + list(entry.get("tags") or []):
        for w in re.split(r"[\s:,\-_.()]+", text.lower()):
            w = w.strip("'’“”\"")
            if len(w) >= 2 and w not in out:
                out.append(w)
    return out


def main():
    pkg, out_path = sys.argv[1], sys.argv[2]
    en = json.load(open(f"{pkg}/en/data.json", encoding="utf-8"))
    es = {e["hexcode"]: e for e in json.load(open(f"{pkg}/es/data.json", encoding="utf-8"))}
    rows = []
    for e in sorted(en, key=lambda x: x.get("order", 10**6)):
        cat = CATEGORIES.get(e.get("group"))
        if cat is None:
            continue
        emoji = normalised(e)
        assert "\t" not in emoji and "\n" not in emoji
        es_words = words(es[e["hexcode"]]) if e["hexcode"] in es else []
        rows.append(f"{emoji}\t{cat}\t{e.get('version', 0)}\t{' '.join(words(e))}\t{' '.join(es_words)}")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("# KeyLingo emoji catalogue, generated by tools/build_emoji_data.py -- do not edit by hand.\n")
        f.write("# From emojibase-data 16.0.3 (MIT) with Unicode CLDR annotations (Unicode License v3);\n")
        f.write("# notices in assets/licenses/emoji-data-notices.txt.\n")
        f.write("# columns: emoji, category, unicode emoji version, english keywords, spanish keywords\n")
        for r in rows:
            f.write(r + "\n")
    print(f"wrote {len(rows)} emoji to {out_path}")


if __name__ == "__main__":
    main()
