#!/usr/bin/env python3
"""
Builds app/src/main/assets/lexicon/es_words.tsv: the Spanish autocomplete
vocabulary, ranked by real usage frequency.

Sources (offline at build time; nothing is fetched by the app):
  * Word frequencies: wordfreq 3.1.1 "large" Spanish list (Robyn Speer et al.).
    Data licence CC BY-SA 4.0 -> es_words.tsv is distributed under CC BY-SA 4.0
    (see app/src/main/assets/licenses/wordfreq-CC-BY-SA-4.0.txt).
  * Spelling validation only (not shipped): RLA-ES Spanish Hunspell dictionary
    (npm dictionary-es 4.0.0, used under MPL-1.1). A word is kept only if
    Hunspell accepts it, so unaccented web misspellings ("asi", "tambien") and
    foreign tokens ("the") are dropped; proper nouns keep their capital
    ("Madrid", "México") when only the capitalised form is valid.

Usage:
  python3 -I tools/build_spanish_lexicon.py <wordfreq data dir> <hunspell dic base (no .dic)> <out.tsv> [count]
Needs: msgpack (pip), hunspell binary.
"""
import gzip, re, subprocess, sys

PROFANITY = {  # recognised (no false autocorrect) but never suggested, like the English list's 'n' flag
    "mierda", "puta", "puto", "putas", "putos", "joder", "jodido", "jodida", "coño", "carajo", "cabrón", "cabrona",
    "pendejo", "pendeja", "pendejos", "gilipollas", "polla", "verga", "chingar", "chingada", "chingado", "culero",
    "mamón", "mamada", "putada", "hijueputa", "malparido", "marica", "maricón", "zorra", "culo",
}
SINGLE_LETTER_WORDS = {"a", "e", "o", "u", "y"}
# Informal chat words Hunspell does not list but people type all the time; kept at their real frequency position.
INFORMAL = {"ok", "jaja", "jajaja", "jeje", "porfa", "finde", "wifi", "app", "chat", "email", "online", "selfie"}


def wordfreq_order(path):
    import msgpack
    with gzip.open(path, "rb") as f:
        data = msgpack.load(f, raw=False)
    for bucket in data[1:]:
        yield from bucket


def hunspell_accepts(words, dic):
    """Returns the subset Hunspell accepts (it echoes correct words with -G)."""
    out = subprocess.run(["hunspell", "-d", dic, "-G", "-i", "utf-8"], input="\n".join(words), capture_output=True, text=True, check=True).stdout
    return set(out.split("\n"))


def main():
    data_dir, dic, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
    count = int(sys.argv[4]) if len(sys.argv) > 4 else 50000
    rx = re.compile(r"^[a-záéíóúüñ]+$")
    candidates = []
    seen = set()
    for w in wordfreq_order(f"{data_dir}/large_es.msgpack.gz"):
        if not rx.match(w) or w in seen:
            continue
        if len(w) == 1 and w not in SINGLE_LETTER_WORDS:
            continue
        seen.add(w)
        candidates.append(w)
        if len(candidates) >= count * 3:
            break
    lower_ok = hunspell_accepts(candidates, dic)
    rejected = [w for w in candidates if w not in lower_ok]
    caps = {w: w[0].upper() + w[1:] for w in rejected}
    caps_ok = hunspell_accepts(list(caps.values()), dic)
    kept = []
    for w in candidates:
        if w in lower_ok or w in INFORMAL:
            kept.append(w)
        elif caps[w] in caps_ok:
            kept.append(caps[w])
        if len(kept) >= count:
            break
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("# KeyLingo Spanish lexicon. Generated by tools/build_spanish_lexicon.py -- do not edit by hand.\n")
        f.write("# Frequency order from wordfreq 3.1.1 (CC BY-SA 4.0, https://github.com/rspeer/wordfreq); spellings validated with\n")
        f.write("# the RLA-ES Hunspell dictionary. This file is licensed CC BY-SA 4.0. columns: word, rank (lower = more common), flags (n = never suggest)\n")
        for rank, w in enumerate(kept, start=1):
            f.write(f"{w}\t{rank}\t{'n' if w.lower() in PROFANITY else ''}\n")
    print(f"candidates {len(candidates)}, accepted lowercase {len(lower_ok & set(candidates))}, capitalised {sum(1 for w in kept if w[0].isupper())}, written {len(kept)}")


if __name__ == "__main__":
    main()
